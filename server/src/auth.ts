import { verifyToken } from '@clerk/backend';
import { createMiddleware } from 'hono/factory';
import { env } from './env.js';

export interface AuthContext {
  /** Stable client identity: Clerk user id when a valid session JWT is sent,
   * otherwise the app's per-install device id. Used for rate limiting only —
   * the server is stateless and stores no per-user data. */
  clientId: string;
  /** Best-effort client IP for per-IP rate limiting — platform-provided headers
   * only (Vercel sets x-vercel-forwarded-for/x-real-ip), never trusted blindly. */
  clientIp: string;
}

/** Prefer Vercel's untamperable forwarding headers, then generic proxies. */
function clientIpFrom(c: { req: { header: (name: string) => string | undefined } }): string {
  return (
    c.req.header('x-vercel-forwarded-for')?.split(',')[0]?.trim() ||
    c.req.header('x-real-ip')?.trim() ||
    c.req.header('x-forwarded-for')?.split(',')[0]?.trim() ||
    'unknown'
  );
}

/**
 * Identifies the calling client for rate limiting + audit.
 * - `Authorization: Bearer <clerk-jwt>` — verified when CLERK_SECRET_KEY is set.
 * - `x-device-id` — stable per-install id generated by the app (secure store).
 * No request is rejected for missing identity: the app works without accounts.
 * If API_SHARED_SECRET is configured, `x-arcfore-key` must match it.
 */
export const identifyClient = createMiddleware<{ Variables: { auth: AuthContext } }>(
  async (c, next) => {
    if (env.apiToken) {
      const key = c.req.header('x-arcfore-key');
      if (key !== env.apiToken) {
        return c.json({ error: 'forbidden', message: 'Invalid API key' }, 403);
      }
    }

    const clientIp = clientIpFrom(c);

    const header = c.req.header('authorization');
    const token = header?.startsWith('Bearer ') ? header.slice(7) : null;
    if (token && env.clerkSecretKey) {
      try {
        const payload = await verifyToken(token, { secretKey: env.clerkSecretKey });
        if (payload.sub) {
          c.set('auth', { clientId: `clerk:${payload.sub}`, clientIp });
          return next();
        }
      } catch {
        // fall through to device id
      }
    }

    const deviceId = c.req.header('x-device-id')?.trim();
    if (deviceId && deviceId.length >= 8 && deviceId.length <= 128) {
      c.set('auth', { clientId: `device:${deviceId}`, clientIp });
      return next();
    }

    c.set('auth', { clientId: 'anonymous', clientIp });
    return next();
  },
);
